// Pre-compute SVG path strings for North America (USA + CAN + MEX) and the cities.
// Run once: `node scripts/build-na-paths.mjs > src/lib/na-paths.ts`
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const __dirname = dirname(fileURLToPath(import.meta.url));
const world = JSON.parse(
  readFileSync(join(__dirname, "..", "src", "data", "world-110m.json"), "utf8"),
);

const VIEW_W = 1000;
const VIEW_H = 520;

const projection = geoMercator()
  .center([-95, 49])
  .scale(560)
  .translate([VIEW_W / 2, VIEW_H / 2]);

const path = geoPath(projection);
const land = feature(world, world.objects.countries);

// ISO 3166-1 numeric: USA=840, CAN=124, MEX=484
const KEEP = new Set(["840", "124", "484"]);
const countries = land.features
  .filter((f) => KEEP.has(String(f.id)))
  .map((f) => ({ id: String(f.id), d: path(f) }));

const cities = [
  { name: "Vancouver", lng: -123.12, lat: 49.28 },
  { name: "Seattle", lng: -122.33, lat: 47.61, isCurrent: true },
  { name: "Ottawa", lng: -75.69, lat: 45.42 },
  { name: "Toronto", lng: -79.38, lat: 43.65 },
].map((c) => {
  const [x, y] = projection([c.lng, c.lat]);
  return {
    name: c.name,
    isCurrent: c.isCurrent,
    x: Math.round(x * 100) / 100,
    y: Math.round(y * 100) / 100,
  };
});

const output = `// Generated by scripts/build-na-paths.mjs — do not edit by hand.
export const NA_VIEWBOX = { width: ${VIEW_W}, height: ${VIEW_H} } as const;

export const NA_COUNTRIES: { id: string; d: string }[] = ${JSON.stringify(countries, null, 2)};

export type ProjectedCity = {
  name: string;
  x: number;
  y: number;
  isCurrent?: boolean;
};

export const NA_CITIES: ProjectedCity[] = ${JSON.stringify(cities, null, 2)};
`;

process.stdout.write(output);
